import { z } from 'zod';

export const ExtractionSchema = z.object({
  title: z.string(),
  summary: z.string(),
  opportunity_type: z.string(),
  organization_name: z.string().nullable(),
  host_institution: z.string().nullable(),
  country: z.string().nullable(),
  region: z.string().nullable(),
  city: z.string().nullable(),
  is_remote: z.boolean().nullable(),
  is_online: z.boolean().nullable(),
  eligible_countries: z.array(z.string()),
  eligible_regions: z.array(z.string()),
  education_levels: z.array(z.string()),
  target_audience: z.array(z.string()),
  fields_of_interest: z.array(z.string()),
  funding_type: z.string(),
  funding_amount: z.string().nullable(),
  currency: z.string().nullable(),
  costs_covered: z.array(z.string()),
  application_deadline: z.string().nullable(),
  start_date: z.string().nullable(),
  end_date: z.string().nullable(),
  duration: z.string().nullable(),
  language_requirements: z.array(z.string()),
  age_min: z.number().nullable(),
  age_max: z.number().nullable(),
  gender_eligibility: z.string().nullable(),
  citizenship_requirements: z.array(z.string()),
  academic_requirements: z.array(z.string()),
  documents_required: z.array(z.string()),
  selection_criteria: z.array(z.string()),
  benefits: z.array(z.string()),
  application_url: z.string().nullable(),
  tags: z.array(z.string()),
  difficulty_level: z.string(),
  competitiveness_level: z.string(),
  confidence_score: z.number().min(0).max(1),
  missing_important_fields: z.array(z.string()),
});

export type ExtractionResult = z.infer<typeof ExtractionSchema>;
